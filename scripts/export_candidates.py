#!/usr/bin/env python3
"""
Export the teammates' political data for the globe UI.

The candidate research app (Next.js + Supabase) keeps its data in two places:

  supabase/seed-data/*.json      politician + cited news summary (the same files
                                 that build supabase/news_seed.sql)
  lib/candidate-profiles.ts      hand-curated funding / issues / career / sources
                                 / myths / status, keyed by slug

The globe UI is a static site (no build step), so it can't import TypeScript or
query Supabase without keys. This script turns both sources into ONE plain
JavaScript module the browser can import directly:

  data/political-data.generated.js

Run it whenever those source files change:

  python3 scripts/export_candidates.py

Nothing in the generated file is edited by hand. Fix data in the source files,
then re-run this script.
"""

import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEED_DIR = ROOT / "supabase" / "seed-data"
PROFILES_TS = ROOT / "lib" / "candidate-profiles.ts"
BUILD_SEED = ROOT / "supabase" / "build-news-seed.mjs"
OUT = ROOT / "data" / "political-data.generated.js"

CITATION_FIELDS = ("n", "title", "url", "source", "published_at")


def fail(msg):
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(1)


def model_label():
    """Reuse the label the Supabase seed builder stamps on its summaries."""
    m = re.search(r'MODEL_LABEL\s*=\s*"([^"]+)"', BUILD_SEED.read_text(encoding="utf-8"))
    return m.group(1) if m else "Research summary"


def load_seed(generated_at):
    politicians, news = [], {}
    files = sorted(SEED_DIR.glob("*.json"))
    if not files:
        fail(f"no seed files found in {SEED_DIR}")
    label = model_label()
    for path in files:
        d = json.loads(path.read_text(encoding="utf-8"))
        p = d["politician"]
        if not p.get("slug") or not p.get("name"):
            fail(f"{path.name}: politician.slug and name are required")
        politicians.append(p)
        citations = [{k: c.get(k) for k in CITATION_FIELDS} for c in d["citations"]]
        news[p["slug"]] = {
            "summary": d["summary"],
            "citations": citations,
            "article_count": len(citations),
            "model": label,
            "generated_at": generated_at,
        }
    return politicians, news


def load_profiles():
    """candidate-profiles.ts is plain object literals; only the import line and
    the type annotation on the export are TypeScript."""
    ts = PROFILES_TS.read_text(encoding="utf-8")
    ts = re.sub(r"^import type [^;]+;\s*$", "", ts, flags=re.M)
    ts, n = re.subn(
        r"export const CANDIDATE_PROFILES\s*:\s*CandidateProfile\[\]\s*=",
        "export const CANDIDATE_PROFILES =",
        ts,
    )
    if n != 1:
        fail("could not find `export const CANDIDATE_PROFILES: CandidateProfile[] =` in candidate-profiles.ts")
    # Any other TypeScript-only syntax would break the browser import.
    for pattern, what in (
        (r"\bas (const|[A-Z]\w*)\b", "`as` cast"),
        (r"\bsatisfies\b", "`satisfies`"),
        (r"\binterface\b", "`interface`"),
    ):
        if re.search(pattern, ts):
            fail(f"candidate-profiles.ts uses TypeScript-only syntax ({what}); extend export_candidates.py")
    return ts.strip()


def main():
    generated_at = datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")
    politicians, news = load_seed(generated_at)
    profiles_js = load_profiles()

    parts = [
        "// GENERATED by scripts/export_candidates.py. DO NOT EDIT BY HAND.",
        "// Sources: supabase/seed-data/*.json and lib/candidate-profiles.ts",
        "// Refresh:  python3 scripts/export_candidates.py",
        "",
        f"export const GENERATED_AT = {json.dumps(generated_at)};",
        "",
        "// Politicians + cited news summaries (same content as supabase/news_seed.sql)",
        f"export const POLITICIANS = {json.dumps(politicians, indent=2, ensure_ascii=False)};",
        "",
        f"export const NEWS_SUMMARIES = {json.dumps(news, indent=2, ensure_ascii=False)};",
        "",
        "// Hand-curated research profiles (verbatim from lib/candidate-profiles.ts)",
        profiles_js,
        "",
    ]
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}  ({OUT.stat().st_size // 1024} KB)")
    print(f"  politicians: {len(politicians)}  news summaries: {len(news)}")
    profile_count = len(re.findall(r"^\s*slug:", profiles_js, flags=re.M))
    print(f"  curated profiles: {profile_count}")


if __name__ == "__main__":
    main()
