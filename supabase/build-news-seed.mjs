// Builds supabase/news_seed.sql from the researched JSON files in
// supabase/seed-data/. Validates each file first (JSON shape, citation
// numbering, every [n] resolves, every citation is used).
//
// Usage: node supabase/build-news-seed.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dataDir = join(here, "seed-data");
const outFile = join(here, "news_seed.sql");
const MODEL_LABEL = "Kiro sub-agent research (news from Oct 10-24, 2026)";

/** Quote a value as a SQL string literal (or NULL). */
function lit(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}

/** Throw with the file name attached if a check fails. */
function check(cond, file, msg) {
  if (!cond) throw new Error(`${file}: ${msg}`);
}

function validate(file, d) {
  const p = d.politician;
  check(p && p.slug && p.name, file, "politician.slug and name are required");
  check(Array.isArray(p.career_history), file, "career_history must be an array");
  check(typeof d.summary === "string" && d.summary.trim(), file, "summary is empty");
  check(Array.isArray(d.citations) && d.citations.length > 0, file, "no citations");

  d.citations.forEach((c, i) => {
    check(c.n === i + 1, file, `citation numbers must be 1..n in order (got ${c.n})`);
    check(/^https:\/\//.test(c.url), file, `citation ${c.n} has a non-https url`);
    check(c.title && c.source, file, `citation ${c.n} needs title and source`);
    check(
      /^2026-10-(1\d|2[0-4])$/.test(c.published_at ?? ""),
      file,
      `citation ${c.n} date ${c.published_at} is outside Oct 10-24, 2026`
    );
  });

  const cited = new Set([...d.summary.matchAll(/\[(\d+)\]/g)].map((m) => Number(m[1])));
  for (const n of cited) {
    check(n >= 1 && n <= d.citations.length, file, `summary cites [${n}] with no source`);
  }
  for (const c of d.citations) {
    check(cited.has(c.n), file, `citation ${c.n} is never referenced in the summary`);
  }
}

const files = readdirSync(dataDir).filter((f) => f.endsWith(".json")).sort();
const records = files.map((file) => {
  const data = JSON.parse(readFileSync(join(dataDir, file), "utf8"));
  validate(file, data);
  return data;
});

const sql = [
  "-- GENERATED by supabase/build-news-seed.mjs. Do not edit by hand.",
  "-- Run AFTER supabase/schema.sql, in the Supabase SQL Editor.",
  "-- Stores only headlines, links, short paraphrased snippets and cited summaries.",
  "begin;",
  "",
];

// Articles are shared across candidates, so de-dupe by URL.
const articles = new Map();
for (const r of records) {
  for (const c of r.citations) {
    if (!articles.has(c.url)) articles.set(c.url, c);
  }
}

sql.push("-- Politicians");
for (const { politician: p } of records) {
  sql.push(
    `insert into public.politicians (slug, name, party, state, current_office, bio, career_history)
values (${lit(p.slug)}, ${lit(p.name)}, ${lit(p.party)}, ${lit(p.state)}, ${lit(p.current_office)}, ${lit(p.bio)}, ${lit(JSON.stringify(p.career_history))}::jsonb)
on conflict (slug) do update set
  name = excluded.name, party = excluded.party, state = excluded.state,
  current_office = excluded.current_office, bio = excluded.bio,
  career_history = excluded.career_history;`
  );
}

sql.push("", "-- Articles (headline, link, short snippet only)");
for (const c of articles.values()) {
  sql.push(
    `insert into public.articles (url, title, snippet, source, published_at)
values (${lit(c.url)}, ${lit(c.title)}, ${lit(c.snippet)}, ${lit(c.source)}, ${lit(c.published_at)})
on conflict (url) do nothing;`
  );
}

sql.push("", "-- Article <-> politician links");
for (const r of records) {
  for (const c of r.citations) {
    sql.push(
      `insert into public.article_politicians (article_id, politician_id)
select a.id, p.id from public.articles a, public.politicians p
where a.url = ${lit(c.url)} and p.slug = ${lit(r.politician.slug)}
on conflict do nothing;`
    );
  }
}

sql.push("", "-- Cited news summaries");
for (const r of records) {
  const citations = r.citations.map(({ n, title, url, source, published_at }) => ({
    n, title, url, source, published_at,
  }));
  sql.push(
    `insert into public.politician_news_summaries (politician_id, summary, citations, article_count, model, generated_at)
select p.id, ${lit(r.summary)}, ${lit(JSON.stringify(citations))}::jsonb, ${citations.length}, ${lit(MODEL_LABEL)}, now()
from public.politicians p where p.slug = ${lit(r.politician.slug)}
on conflict (politician_id) do update set
  summary = excluded.summary, citations = excluded.citations,
  article_count = excluded.article_count, model = excluded.model,
  generated_at = excluded.generated_at;`
  );
}

sql.push("", "commit;", "");
writeFileSync(outFile, sql.join("\n"), "utf8");

console.log(`Validated ${records.length} files: ${files.join(", ")}`);
console.log(`Unique articles: ${articles.size}`);
console.log(`Wrote ${outFile}`);
